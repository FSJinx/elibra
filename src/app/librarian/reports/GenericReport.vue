<template>
  <div class="size-full flex flex-col overflow-hidden">
    <SectionHeader :title="title" :description="`Generate ${title.toLowerCase()} data scoped to this library`" :icon="icon">
      <div class="flex items-center ml-auto">
        <NewGenericReport :type="reportType" :title="title" @refresh="search" />
      </div>
    </SectionHeader>

    <div class="flex-1 flex p-5 overflow-hidden">
      <Table title="Report History" subtitle="This library's recent report extractions" :data="pagination">
        <template #header>
          <Form class="flex items-center justify-end w-full gap-2 flex-wrap" @submit="search">
            <Input class="max-w-100" type="text" placeholder="Search by reference number" v-model="params.query" />
            <Button type="submit">Search</Button>
          </Form>
        </template>
        <Thead>
          <tr>
            <Th>No</Th>
            <Th>Report ID</Th>
            <Th>Date Generated</Th>
            <Th>Generated by</Th>
            <Th>Type</Th>
            <Th>Actions</Th>
          </tr>
        </Thead>
        <Tbody :data="pagination?.data" :loading="loading">
          <Tr v-for="(item, index) in pagination?.data" :key="item.id">
            <Td :data="(pagination?.from ?? 0) + index" />
            <Td :data="item.reference" />
            <Td :data="parse.formatTimeAgo(item.created_at)" />
            <Td :data="item.generator?.name?.full" />
            <Td class="uppercase">
              <Icon :icon="`filetype-${item.format}`" />
              {{ item.format }}
            </Td>
            <Td>
              <Button size="sm" left-icon="download" @click="attachment.download(item.file)">Download</Button>
            </Td>
          </Tr>
        </Tbody>
      </Table>
    </div>
  </div>
</template>

<script setup lang="ts">
import NewGenericReport from '@/app/librarian/reports/modals/NewGenericReport.vue'

const route = useRoute()
const attachment = attachmentStore()
const report = reportStore()
const parse = useParser()

const reportType = computed(() => String(route.meta.reportType ?? ''))
const title = computed(() => String(route.meta.title ?? 'Report'))
const icon = computed(() => String(route.meta.icon ?? 'file-earmark-bar-graph'))
const pagination = ref<Pagination>()
const loading = ref(false)
const params = reactive<Partial<ReportParams>>({
  type: reportType.value,
  query: '',
})

watch(reportType, (type) => {
  params.type = type
  search()
}, { immediate: true })

async function search() {
  loading.value = true
  try {
    const res = await report.fetch(params)
    pagination.value = res.data
  } finally {
    loading.value = false
  }
}
</script>
