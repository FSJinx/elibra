<template>
  <div class="size-full flex flex-col overflow-hidden">
    <SectionHeader title="Circulation Report" description="Generate circulation reports for your library" icon="bar-chart-line">
      <div class="flex items-center ml-auto">
        <NewCirculationReport />
      </div>
    </SectionHeader>

    <div class="flex-1 flex p-5">
      <Table title="Report History" subtitle="Your library's recent report extractions" :data="pagination">
        <template #header>
          <Form class="flex items-center justify-end w-full gap-2 flex-wrap" id="search-report" @submit="search">
            <Input class="max-w-100" type="text" placeholder="Search by reference number" v-model="params.query" />
            <Button type="submit">Search</Button>
          </Form>
        </template>
        <Thead>
          <tr>
            <Th>No</Th>
            <Th>Report ID</Th>
            <Th>Date Generated</Th>
            <Th>Generated by</Th>
            <Th>Actions</Th>
          </tr>
        </Thead>
        <Tbody :data="pagination?.data" :loading>
          <Tr v-for="(item, index) in pagination?.data" :key="index">
            <Td :data="(pagination?.from ?? 0) + index" />
            <Td :data="item.reference" />
          </Tr>
        </Tbody>
      </Table>
    </div>
  </div>
</template>

<script setup lang="ts">
import NewCirculationReport from '@/app/librarian/reports/circulation/modals/NewCirculationReport.vue'

const route = useRoute()
const report = reportStore()

const pagination = ref<Pagination>()
const loading = ref<boolean>(false)
const params = reactive<Partial<ReportParams>>({})

async function search() {
  loading.value = true
  try {
    const res = await report.fetch(params)
    pagination.value = res.data
  } finally {
    loading.value = false
  }
}
</script>

